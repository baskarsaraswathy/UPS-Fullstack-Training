// Addition
let a = 10;
let b = 20;

console.log("Addition: " + (a + b));

// Even or Odd
let number = 10;

if (number % 2 == 0) {
    console.log("Even Number");
} else {
    console.log("Odd Number");
}

// Positive or Negative
let num = -5;

if (num > 0) {
    console.log("Positive");
} else if (num < 0) {
    console.log("Negative");
} else {
    console.log("Zero");
}
